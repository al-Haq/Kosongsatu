// Locale used for dates on each document language.
export const LOCALES = { en: "en-MY", ms: "ms-MY", zh: "zh-MY" };
// t(lang)(key, { name: value }) with English as the fallback for missing keys.
export function labels(lang = "en") {
  const dict = LABELS[lang] || en;
  return (key, values = {}) =>
    String(dict[key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (m, k) => (k in values ? String(values[k]) : m));
}
// Upper-case title for a document kind ("INVOICE", "INVOIS", "发票").
export const titleFor = (lang, kind) => labels(lang)("kind_" + kind).toUpperCase();
export const statusLabel = (lang, status) => labels(lang)("st_" + status);
