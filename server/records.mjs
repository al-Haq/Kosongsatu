import { chmodSync } from "node:fs";
import { today, check, date, integer, addDays } from "./domain.mjs";
export function migrateRecords(db, path) {
  const version = db.prepare("PRAGMA user_version").get().user_version;
  if (version >= 4) return;
  if (
    path !== ":memory:" &&
    db.prepare("SELECT count(*) n FROM documents").get().n
  ) {
    const snapshot = path + ".pre-v4-" + Date.now() + ".sqlite";
    db.prepare("VACUUM INTO ?").run(snapshot);
    chmodSync(snapshot, 0o600);
  }
  db.exec("BEGIN IMMEDIATE");
  try {
    db.exec(`
 ALTER TABLE clients ADD COLUMN archived INTEGER NOT NULL DEFAULT 0;
 PRAGMA user_version=4; COMMIT;`);
  } catch (e) {
    db.exec("ROLLBACK");
    throw e;
  }
}
// Record maintenance: archive, guarded deletes, schedule edits and document duplication.
// Issued documents, receipts and audit history are never deleted.
export function attachRecords(Store) {
  const originalDocument = Store.prototype.saveDocument,
    originalSchedule = Store.prototype.saveSchedule,
    originalOpportunity = Store.prototype.saveOpportunity;
  const active = (store, clientId) =>
    check(
      !store.client(clientId).archived,
      "This client is archived. Restore the client before creating new records.",
      409,
    );
  Object.assign(Store.prototype, {
    saveDocument(b, idv) {
      const existing = idv
        ? this.db.prepare("SELECT client_id FROM documents WHERE id=?").get(idv)
        : null;
      if (!existing || existing.client_id !== b.client_id)
        active(this, b.client_id);
      return originalDocument.call(this, b, idv);
    },
    saveSchedule(b) {
      active(this, b.client_id);
      return originalSchedule.call(this, b);
    },
    saveOpportunity(b, sid) {
      if (!sid) active(this, b.client_id);
      return originalOpportunity.call(this, b, sid);
    },
    archiveClient(cid, archived) {
      return this.tx(() => {
        const c = this.client(cid);
        check(typeof archived === "boolean", "Choose archive or restore.");
        if (archived)
          check(
            !this.db
              .prepare(
                "SELECT 1 FROM schedules WHERE client_id=? AND active=1",
              )
              .get(cid),
            "Pause this client's recurring schedules before archiving.",
            409,
          );
        this.db
          .prepare("UPDATE clients SET archived=? WHERE id=?")
          .run(archived ? 1 : 0, cid);
        this.audit(
          archived ? "client.archived" : "client.restored",
          cid,
          c.name,
          { archived: c.archived },
          { archived: archived ? 1 : 0 },
        );
        return this.client(cid);
      });
    },
    deleteClient(cid) {
      return this.tx(() => {
        const c = this.client(cid);
        for (const [table, label] of [
          ["documents", "documents"],
          ["cash_receipts", "receipts"],
          ["schedules", "recurring schedules"],
          ["sales_opportunities", "sales opportunities"],
          ["customer_pos", "customer POs"],
        ])
          check(
            !this.db
              .prepare(`SELECT 1 FROM ${table} WHERE client_id=?`)
              .get(cid),
            `This client has ${label}. Archive the client instead.`,
            409,
          );
        this.db.prepare("DELETE FROM clients WHERE id=?").run(cid);
        this.audit("client.deleted", cid, c.name, c, null);
      });
    },
    deleteService(sid) {
      return this.tx(() => {
        const s = this.db.prepare("SELECT * FROM services WHERE id=?").get(sid);
        check(s, "Service not found.", 404);
        check(
          !this.db.prepare("SELECT 1 FROM schedules WHERE service_id=?").get(sid),
          "A recurring schedule uses this service. Mark it inactive instead.",
          409,
        );
        // Documents copy line text and rates, so they do not depend on the catalog row.
        this.db.prepare("DELETE FROM services WHERE id=?").run(sid);
        this.audit("service.deleted", sid, s.name, s, null);
      });
    },
    deleteDraft(did) {
      return this.tx(() => {
        const d = this.db.prepare("SELECT * FROM documents WHERE id=?").get(did);
        check(d, "Document not found.", 404);
        check(
          d.state === "draft",
          "Only drafts can be deleted. Void an issued document instead.",
          409,
        );
        for (const [sql, message] of [
          [
            "SELECT 1 FROM schedule_runs WHERE invoice_id=?",
            "This draft was generated by a recurring schedule. Edit it instead of deleting so the period stays billed.",
          ],
          [
            "SELECT 1 FROM customer_pos WHERE invoice_id=?",
            "This draft is linked to a customer PO. Edit it instead.",
          ],
          [
            "SELECT 1 FROM sales_opportunities WHERE quote_id=?",
            "This draft is linked to a sales opportunity. Edit it instead.",
          ],
        ])
          check(!this.db.prepare(sql).get(did), message, 409);
        this.db.prepare("DELETE FROM documents WHERE id=?").run(did);
        this.audit("draft.deleted", did, d.kind, {
          kind: d.kind,
          client_id: d.client_id,
          items: JSON.parse(d.items),
          total: d.total,
          source_quote: d.source_quote,
        });
      });
    },
    duplicateDocument(did) {
      return this.tx(() => {
        const d = this.document(did);
        const c = this.client(d.client_id);
        const issue = today();
        const copy = this.saveDocument({
          kind: d.kind,
          client_id: d.client_id,
          issue_date: issue,
          due_date: addDays(issue, d.kind === "quote" ? 14 : c.terms),
          items: d.items.map((i) => ({
            description: i.description,
            quantity: String(i.quantity),
            rate: (i.rate / 100).toFixed(2),
            tax_rate: i.tax_rate ?? 0,
          })),
          discount: (d.discount / 100).toFixed(2),
          notes: d.notes,
          terms: d.terms,
        });
        this.audit("document.duplicated", copy.id, d.number || d.id);
        return copy;
      });
    },
    updateSchedule(sid, b) {
      return this.tx(() => {
        const s = this.db.prepare("SELECT * FROM schedules WHERE id=?").get(sid);
        check(s, "Schedule not found.", 404);
        const service = this.db
          .prepare("SELECT * FROM services WHERE id=? AND active=1")
          .get(b.service_id ?? s.service_id);
        check(service, "Choose an active service.");
        const next_date = date(b.next_date ?? s.next_date);
        const last = this.db
          .prepare("SELECT max(period) p FROM schedule_runs WHERE schedule_id=?")
          .get(sid).p;
        check(
          !last || next_date > last,
          "The next run must be after the last generated period.",
        );
        const out = {
          service_id: service.id,
          next_date,
          terms: integer(b.terms ?? s.terms, 0, 365),
          // Keep the original anchor (e.g. the 30th clamped to 28 Feb) unless the date was moved.
          anchor_day:
            next_date === s.next_date ? s.anchor_day : Number(next_date.slice(-2)),
          month_end:
            b.month_end === undefined ? s.month_end : b.month_end === true ? 1 : 0,
        };
        this.db
          .prepare(
            "UPDATE schedules SET service_id=:service_id,next_date=:next_date,terms=:terms,anchor_day=:anchor_day,month_end=:month_end WHERE id=:id",
          )
          .run({ ...out, id: sid });
        this.audit("schedule.changed", sid, "Schedule edited", s, out);
        return this.db.prepare("SELECT * FROM schedules WHERE id=?").get(sid);
      });
    },
    deleteSchedule(sid) {
      return this.tx(() => {
        const s = this.db.prepare("SELECT * FROM schedules WHERE id=?").get(sid);
        check(s, "Schedule not found.", 404);
        check(
          !this.db
            .prepare("SELECT 1 FROM schedule_runs WHERE schedule_id=?")
            .get(sid),
          "This schedule has generated invoices. Pause it instead to keep its history.",
          409,
        );
        this.db.prepare("DELETE FROM schedules WHERE id=?").run(sid);
        this.audit("schedule.deleted", sid, "", s, null);
      });
    },
    deleteOpportunity(oid) {
      return this.tx(() => {
        const o = this.db
          .prepare("SELECT * FROM sales_opportunities WHERE id=?")
          .get(oid);
        check(o, "Sales opportunity not found.", 404);
        check(
          !o.quote_id,
          "This opportunity has a quotation. Mark it lost instead.",
          409,
        );
        this.db.prepare("DELETE FROM sales_opportunities WHERE id=?").run(oid);
        this.audit("sales.deleted", oid, o.title, o, null);
      });
    },
  });
}
